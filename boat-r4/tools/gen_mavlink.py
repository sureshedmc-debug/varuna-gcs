"""
Writes boat-r4/varuna_boat_brain/mav_msgs.h: the MAVLink messages the UNO R4
boat brain speaks, generated from pymavlink's own definitions (the same ones
the laptop's boat program uses), so every field order, length and CRC extra
matches exactly. Re-run after changing MESSAGES:

    py boat-r4/tools/gen_mavlink.py
"""

import os

from pymavlink.dialects.v20 import ardupilotmega as mav

MESSAGES = [
    # in
    "HEARTBEAT", "GPS_INPUT", "COMMAND_LONG", "COMMAND_INT", "SET_MODE", "RC_CHANNELS_OVERRIDE",
    "PARAM_REQUEST_READ", "PARAM_REQUEST_LIST", "PARAM_SET",
    "MISSION_COUNT", "MISSION_ITEM_INT", "MISSION_ITEM", "MISSION_REQUEST_LIST", "MISSION_REQUEST_INT",
    "MISSION_REQUEST", "MISSION_ACK", "MISSION_SET_CURRENT", "MISSION_CLEAR_ALL",
    "SET_POSITION_TARGET_GLOBAL_INT", "REQUEST_DATA_STREAM",
    # out
    "SYS_STATUS", "GPS_RAW_INT", "ATTITUDE", "GLOBAL_POSITION_INT", "MISSION_CURRENT", "SERVO_OUTPUT_RAW",
    "RC_CHANNELS", "VFR_HUD", "COMMAND_ACK", "STATUSTEXT", "PARAM_VALUE", "MISSION_ITEM_REACHED",
    "HOME_POSITION", "POWER_STATUS", "NAV_CONTROLLER_OUTPUT",
]

SIZES = {"uint8_t": 1, "int8_t": 1, "char": 1, "uint16_t": 2, "int16_t": 2, "uint32_t": 4, "int32_t": 4,
         "float": 4, "uint64_t": 8, "int64_t": 8, "double": 8}


def cls(name):
    return getattr(mav, f"MAVLink_{name.lower()}_message")


def main():
    out = [
        "// GENERATED by boat-r4/tools/gen_mavlink.py from pymavlink "
        "(ardupilotmega, MAVLink 2) - do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "#include <string.h>",
        "",
    ]
    crc_cases, len_cases = [], []
    max_len = 0
    for name in MESSAGES:
        c = cls(name)
        types = dict(zip(c.fieldnames, c.fieldtypes))
        arrays = dict(zip(c.ordered_fieldnames, c.array_lengths))
        low = name.lower()
        off, fields = 0, []
        for f in c.ordered_fieldnames:
            t, n = types[f], arrays[f]
            size = SIZES[t] * (n or 1)
            fields.append((f, t, n, off, size))
            off += size
        total = off
        max_len = max(max_len, total)
        out.append(f"#define MAV_ID_{name} {c.id}")
        out.append(f"#define MAV_CRC_{name} {c.crc_extra}")
        out.append(f"#define MAV_LEN_{name} {total}")
        out.append(f"typedef struct {{")
        for f, t, n, _, _ in sorted(fields, key=lambda x: c.fieldnames.index(x[0])):
            ctype = "char" if t == "char" else t
            out.append(f"  {ctype} {f}{f'[{n}]' if n else ''};")
        out.append(f"}} mav_{low}_t;")
        # unpack: zero-fill the trimmed tail first (MAVLink 2 drops trailing zeros)
        out.append(f"static inline void mav_unpack_{low}(const uint8_t* p, uint8_t len, mav_{low}_t* m) {{")
        out.append(f"  uint8_t b[{total}]; memset(b, 0, sizeof b); memcpy(b, p, len < {total} ? len : {total});")
        for f, t, n, o, size in fields:
            out.append(f"  memcpy({'' if n else '&'}m->{f}, b + {o}, {size});")
        out.append("}")
        out.append(f"static inline uint8_t mav_pack_{low}(uint8_t* p, const mav_{low}_t* m) {{")
        for f, t, n, o, size in fields:
            out.append(f"  memcpy(p + {o}, {'' if n else '&'}m->{f}, {size});")
        out.append(f"  return {total};")
        out.append("}")
        out.append("")
        crc_cases.append(f"    case {c.id}: return {c.crc_extra};")
    out.append(f"#define MAV_MAX_PAYLOAD {max_len}")
    out.append("/** CRC extra of a message this brain understands, or -1 (then it is ignored). */")
    out.append("static inline int mav_crc_extra(uint32_t id) {")
    out.append("  switch (id) {")
    out += crc_cases
    out.append("    default: return -1;")
    out.append("  }")
    out.append("}")
    path = os.path.join(os.path.dirname(__file__), "..", "varuna_boat_brain", "mav_msgs.h")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.normpath(path)}: {len(MESSAGES)} messages, max payload {max_len}")


if __name__ == "__main__":
    main()
